-- Pre-inscripciones UPAC Allstars. Mismos campos que el formulario de Google
-- "Pre-Inscripciones UPAC Allstars 2027". Nombre de tabla con la convención
-- <app>_<modelo> que usa la base de sphere.
CREATE TABLE IF NOT EXISTS inscripciones_preinscripcion (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    temporada           smallint     NOT NULL,

    -- 1. Datos del deportista
    nombre_completo     varchar(150) NOT NULL,
    fecha_nacimiento    date         NOT NULL,
    edad_temporada      smallint     NOT NULL CHECK (edad_temporada BETWEEN 1 AND 100),

    -- 2. Información deportiva
    experiencia         varchar(20)  NOT NULL CHECK (experiencia IN ('sin_experiencia', 'con_experiencia')),
    ultimo_equipo       varchar(200) NOT NULL,
    rol                 varchar(10)  NOT NULL CHECK (rol IN ('base', 'flyer', 'ambos')),
    nivel_gimnasia      varchar(100) NOT NULL,
    condicion_edad      varchar(10)  NOT NULL CHECK (condicion_edad IN ('menor_18', 'mayor_18')),

    -- 3a. Contacto del deportista (18 años o más)
    telefono            varchar(20),
    email               varchar(254),

    -- 3b. Datos del apoderado (menores de 18)
    apoderado_nombre    varchar(150),
    apoderado_telefono  varchar(20),
    apoderado_email     varchar(254),

    estado              varchar(20)  NOT NULL DEFAULT 'pendiente',
    created_at          timestamptz  NOT NULL DEFAULT now(),

    CONSTRAINT inscripciones_preinscripcion_contacto CHECK (
        (condicion_edad = 'mayor_18' AND telefono IS NOT NULL AND email IS NOT NULL)
        OR
        (condicion_edad = 'menor_18' AND apoderado_nombre IS NOT NULL
            AND apoderado_telefono IS NOT NULL AND apoderado_email IS NOT NULL)
    )
);

-- Evita que el mismo deportista se pre-inscriba dos veces en la misma temporada
CREATE UNIQUE INDEX IF NOT EXISTS inscripciones_preinscripcion_unica
    ON inscripciones_preinscripcion (temporada, lower(nombre_completo), fecha_nacimiento);

CREATE INDEX IF NOT EXISTS inscripciones_preinscripcion_created_at
    ON inscripciones_preinscripcion (created_at DESC);
